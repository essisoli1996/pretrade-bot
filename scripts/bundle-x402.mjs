// x402 Cloud uploads each service's index.ts alone (no imports). The newer paid services reuse the bot's own
// modules instead of a port: this script wraps each bot module in its own scope (so names can't collide),
// rewires its imports, and writes the bundle between the "BEGIN bundle" / "END bundle" markers of the service.
// One source of truth: the endpoint runs exactly the code the bot runs.
//   node scripts/bundle-x402.mjs          write the bundles
//   node scripts/bundle-x402.mjs --check  fail if any bundle is out of date (runs in npm test)
import { readFileSync, writeFileSync } from "node:fs";

const SERVICES = {
  "trade-plan": ["v4hooks", "sim-runtime", "sim"],
  "stock-check": ["stocks"],
  "approvals": ["approvals"],
};
const BEGIN = "// ── BEGIN bundle ──", END = "// ── END bundle ──";

function wrap(name) {
  let src = readFileSync(new URL(`../bot/${name}.mjs`, import.meta.url), "utf8");
  const exports = [...src.matchAll(/^export (?:async )?(?:function|const|let) (\w+)/gm)].map((m) => m[1]);
  src = src.replace(/^import \{([^}]+)\} from "\.\/([\w-]+)\.mjs";$/gm, (_, names, mod) => `const {${names}} = __${mod.replace(/-/g, "_")};`);
  if (/^import /m.test(src)) throw new Error(`bot/${name}.mjs has an import the bundler can't rewire`);
  src = src.replace(/^export /gm, "");
  return `const __${name.replace(/-/g, "_")} = (() => {\n${src.trim()}\nreturn { ${exports.join(", ")} };\n})();`;
}

let stale = 0;
for (const [svc, mods] of Object.entries(SERVICES)) {
  const file = new URL(`../x402/${svc}/index.ts`, import.meta.url);
  const cur = readFileSync(file, "utf8");
  const b = cur.indexOf(BEGIN), e = cur.indexOf(END);
  if (b < 0 || e < b) throw new Error(`x402/${svc}/index.ts has no bundle markers`);
  const body = `${BEGIN} (generated by scripts/bundle-x402.mjs from ${mods.map((m) => `bot/${m}.mjs`).join(", ")}; do not edit)\n${mods.map(wrap).join("\n\n")}\n`;
  const next = cur.slice(0, b) + body + cur.slice(e);
  if (next === cur) continue;
  if (process.argv.includes("--check")) { console.error(`x402/${svc}/index.ts bundle is out of date: run node scripts/bundle-x402.mjs`); stale++; }
  else { writeFileSync(file, next); console.log(`bundled x402/${svc}/index.ts`); }
}
process.exit(stale ? 1 : 0);
