const BAD = ["phishing_activities", "stealing_attack", "blacklist_doubt", "cybercrime", "money_laundering", "honeypot_related_address", "fake_kyc", "sanctioned", "financial_crime", "fake_token"];

export default async function handler(req: Request): Promise<Response> {
  const url = new URL(req.url);
  const wallet = (url.searchParams.get("wallet") ?? url.searchParams.get("address") ?? "").trim().toLowerCase();
  const chain = (url.searchParams.get("chain") ?? "robinhood").toLowerCase();
  if (!/^0x[0-9a-f]{40}$/.test(wallet)) return bad(400, "invalid_wallet", "Pass ?wallet=0x…");
  if (!RPCS[chain]) return bad(400, "unsupported_chain", `Supported: ${Object.keys(RPCS).join(", ")}`);
  const rpcFor = (c: string) => async (method: string, params: unknown[]) => (await http(RPCS[c], { jsonrpc: "2.0", id: 1, method, params })).json ?? {};
  const reputation = async (a: string) => {
    const r = await http(`https://api.gopluslabs.io/api/v1/address_security/${a}?chain_id=${GOPLUS_ID[chain]}`);
    const x = r.json?.result ?? {};
    return BAD.filter((k) => x[k] === "1" || x[k] === 1).map((k) => k.replace(/_/g, " "));
  };
  const audit = __approvals.makeApprovals({ rpcFor, http, known: KNOWN, reputation }).audit(wallet, chain);
  const r: any = await Promise.race([audit, new Promise((res) => setTimeout(() => res(null), 25000))]);
  if (!r) return bad(504, "scan_timeout", "The chain was too slow to scan. You were not charged.");
  if (r.error) return bad(502, "scan_unavailable", `${r.error}. You were not charged.`);
  return Response.json({ ...r, worthRevoking: r.approvals.filter((x: any) => x.risk !== "low").length, checkedAt: new Date().toISOString(), disclaimer: DISCLAIMER });
}
